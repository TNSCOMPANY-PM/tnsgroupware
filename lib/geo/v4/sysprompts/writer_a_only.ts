export function buildWriterAOnlyUserPrompt(args: {
  topic: string;
  industry: string;
  a_only_facts: unknown;
}): string {
  return `# 토픽
${args.topic}

# industry
${args.industry}

# a_only_facts (IndustryAnalysisFacts — 분포/ranking/outlier)
\`\`\`json
${JSON.stringify(args.a_only_facts, null, 2)}
\`\`\`

위 업종 분석 데이터로 본문을 작성하세요.
★ 단일 brand 비교 X — 분석 단위는 항상 "${args.industry} N개 brand".
★ "본사 데이터" / "브로셔" / "POS" 등 C 출처 표기 절대 X (정보공개서만).
★ frontmatter / FAQ 출력 X (코드에서 별도 생성). 첫 줄은 본문 훅 (헤더 X).
★ display 값 변형 / 자릿수 재계산 절대 X.
★ p25/p50 약어 X — 자연어 ("중앙값" / "상위 10%") 사용.
★ σ / 표준편차 / 정규분포 / outlier / 시그마 본문 등장 X — 평균과 두드러지게 차이 나는 brand 식 자연어로.
★ "[블럭 A/B/C]" / "블럭 B —" 본문 라벨 X — 자연 헤더 (\`## 분포 분석\` 등).
★ metric label "(2024)" 괄호 인용 X — "2024년" 자연어로.
★ 훅 유형·헤더 문구는 이 데이터가 가장 강하게 말하는 것으로 선택 (시리즈 반복감 방지 — v4-20).
★ topic 에 지역명이 있으면 분포(전국 모집단)와 랭킹(지역 기준)의 기준 차이를 분포 섹션 첫 문단에 한 문장으로 명시 (v4-20).`;
}
